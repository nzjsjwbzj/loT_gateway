void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
	/**
	 * 
	 * @brief USART1 ????????????????
	 *
	 * ??????????????????????? USART1 ?????????????????????????????^
	 *
	 * ??????(USART_RX_STA)?????????
	 * - bit15 (0x8000) : ???????????????????????? CR+LF ???????
	 * - bit14 (0x4000) : ?????? 0x0D (CR) ???????????????? 0x0A (LF)
	 * - bits13..0 (0x3FFF) : ???????????????????????
	 *
	 * ?????????????
	 * 1. ??? huart->Instance == USART1 ?????????????????????? USART1 ???????
	 * 2. ?????????????USART_RX_STA & 0x8000 == 0??????????????
	 *    a) ??????????? CR??USART_RX_STA & 0x4000????
	 *       - ????????? aRxBuffer[0] ? LF (0x0A)????????? bit15(0x8000) ???????????????????
	 *       - ?????????????????????????????? USART_RX_STA???????????????????????????
	 *    b) ???????????? CR??
	 *       - ?????????? CR (0x0D)???????? CR ?????bit14????????????????? LF??
	 *       - ???????????????? USART_RX_BUF ???????? (USART_RX_STA & 0x3FFF)???????? USART_RX_STA ??????????
	 *         ????????????????????? (USART_REC_LEN - 1)???? USART_RX_STA ????? 0???????????????????????????
	 *
	 * ????????????????
	 * - aRxBuffer[0] ??????????????????????
	 * - USART_RX_BUF ?????????? USART_REC_LEN ????????????
	 * - ??????? CR (0x0D) + LF (0x0A) ????????????
	 * - ?? CR ????????? LF?????????????????????????????????????????????????????????????????????????????????
	 *
	 * ????????
	 * - ???????????0x8000??0x4000??0x3FFF??0x0D??0x0A????????????????????????
	 * - ?????????????????????????????????????????????????
	 * - ??????????????????????????????????????????
	 */
	if(huart->Instance==USART1)//????????1
	{
		if((USART_RX_STA&0x8000)==0)//?????????
		{
			if(USART_RX_STA&0x4000)//???????0x0d
			{
				if(aRxBuffer[0]!=0x0a)USART_RX_STA=0;//???????,??????
				else USART_RX_STA|=0x8000;	//????????? 
			}
			else //??????0X0D
			{	
				if(aRxBuffer[0]==0x0d)USART_RX_STA|=0x4000;
				else
				{
					USART_RX_BUF[USART_RX_STA&0X3FFF]=aRxBuffer[0] ;
					USART_RX_STA++;
					if(USART_RX_STA>(USART_REC_LEN-1))USART_RX_STA=0;//???????????,??????????	  
				}		 
			}
		}

	}

	else if(huart->Instance == ATK_MW8266D_UART_INTERFACE)                 /* ?????ATK-MW8266D UART */
	{
		                           /* ??????????????? */
	}
}
 
